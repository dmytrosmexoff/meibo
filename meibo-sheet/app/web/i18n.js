const I18N_RX = [
  [/^欠席（(\d+)）$/, "Отсутствуют ($1)"],
  [/^印刷キュー（(\d+)\s*\/\s*15）$/, "Очередь печати ($1 / 15)"]
];
function i18nText(s) {
  const k = s.trim();
  if (!k) return null;
  if (Object.prototype.hasOwnProperty.call(I18N_RU, k)) return s.replace(k, I18N_RU[k]);
  for (const [rx, rep] of I18N_RX) {
    if (rx.test(k)) return s.replace(k, k.replace(rx, rep));
  }
  return null;
}
// translates the visible text of the page (not the sheet, not the printed forms)
function i18nApply(root) {
  if (LANG !== 'ru' || !root) return;
  const skip = el => el.nodeType === 1 && (el.id === 'sheet' || el.id === 'qprint' ||
    el.classList.contains('fpage') || el.classList.contains('qpage'));
  const walk = node => {
    if (skip(node)) return;
    for (const c of [...node.childNodes]) {
      if (c.nodeType === 3) {
        const r = i18nText(c.nodeValue);
        if (r !== null) c.nodeValue = r;
      } else if (c.nodeType === 1 && !skip(c)) {
        for (const a of ['placeholder', 'title']) {
          if (c.hasAttribute(a)) {
            const r = i18nText(c.getAttribute(a));
            if (r !== null) c.setAttribute(a, r);
          }
        }
        walk(c);
      }
    }
  };
  walk(root);
}
